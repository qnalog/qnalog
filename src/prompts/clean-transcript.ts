// 清稿（高保真清理转写）专用提示词。
// 清稿 ≠ 纪要，也 ≠ 原始逐字稿：它保留有效发言的顺序、细节和语气，只清理阅读噪声。
// 它不以缩短为目标；删掉的是纯口语填充和确切重复，不是例子、旁支解释或讨论过程。

export const CLEAN_TRANSCRIPT_SYSTEM =
  "你是一位资深的口述记录编辑。你的任务是把原始语音转写整理成高保真、连续、可核对的清稿：保留有效发言的先后顺序、事实、数字、案例、解释、分歧、语气和关键原话，只清理口头填充、结巴、确切重复与作废的自我更正。这不是纪要：不摘要、不提炼结论、不重组议题，也不以缩短篇幅为目标。读者应当能从清稿中还原会议实际讲了什么，同时不必忍受原始 ASR 的阅读噪声。";

// 多声道硬件（如 DJI 一收多发）分离出的说话人是既定事实，不能让模型再去猜。
export function buildKnownSpeakerClause(speakerLabels: string[]): string {
  const labels = (speakerLabels || [])
    .map((item) => String(item || "").trim())
    .filter(Boolean);
  if (!labels.length) return "";
  return `【说话人已确认——必须遵守】
- 转写标签及其姓名映射：${labels.join("、")}。
- 有真实姓名的说话人，整理时直接使用真实姓名；未填写姓名的继续使用「说话人N」。
- 不得根据语义重新猜测、交换或合并发言归属。姓名只来自用户确认，发言归属只来自转写标签。`;
}

export function buildCleanTranscriptChunkPrompt(
  joinedChunk: string,
  partIndex: number,
  partTotal: number,
  timeRange: string,
  speakerLabels: string[] = [],
): string {
  const knownSpeakers = buildKnownSpeakerClause(speakerLabels);
  const partLine = partTotal > 1
    ? `请把下面这场录音的**第 ${partIndex}/${partTotal} 部分**（时间段约 ${timeRange}）改写成通顺可读的书面文字稿。只改写这一部分，不复述其它部分，不要为这一部分写小结或总览。`
    : `请把下面这场录音的分段转写改写成一篇通顺、可读的书面文字稿（时间段约 ${timeRange}）。`;
  return `${partLine}
${knownSpeakers ? `\n${knownSpeakers}\n` : ""}
【清理范围】
- 把口语句法整理成通顺句子：补必要标点，理顺明显倒装，合并被打断后重新说完整的同一句话；不要为了文采改写说话人的观点和语气。
- 按话题与发言**自然分段**：同一个人连续讲的整合成连贯段落，换人另起一段；不要堆成一大坨，也不要碎成一句一行。
- **可以删除**：没有语义的语气词、结巴、紧邻的逐字重复、自我更正中明确作废的半句，以及完全不承载信息的寒暄。
- **必须保留**：事实与数字、完整的例子和反例、旁支解释、因果链、类比、追问、犹豫所反映的立场、观点转折、讨论过程和有内容的题外话。不要因为内容看起来“跑题”就删除。
- 明显 ASR 错字只有在上下文足以确认时才校正；无法确认时保留原表述并标注「待核对」。

【忠实的边界——实质忠实，不是逐字】
- 「忠实」= 不漏任何有信息量的内容，不改变原意，不调换发言先后，不把不同人的观点合并，不替任何人补造没说过的话。
- 清稿不追求固定压缩率。有效内容整理后应与原始有效发言保持接近的体量；不允许把一段完整讨论压成一句概述。
- 关键原话、独特措辞和能体现态度的短句可以直接保留。
- 拿不准是否应该删除时，一律保留，只做必要的标点和语序清理。

【格式】
- 保留说话人：用「**说话人**：」起段${knownSpeakers ? "（照抄上方已确定的说话人标签）" : "（转写里没有清晰说话人时，按语义分段即可，**不要硬编人名**）"}。
- 时间锚点：只在**话题切换或较大时间跳跃**处用 \`[MM:SS]\` 标一下（取自下方各段起始时间），便于回母本核对；**不要每句都标、不要打断句子**。
- 纯书面正文：不要 YAML frontmatter、不要顶部总览／摘要、不要列点和小标题、不要代码围栏、不要任何前言或解释。

【本部分分段转写】
${joinedChunk}`;
}
